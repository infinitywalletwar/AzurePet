namespace InPolsure.Ui.Components;

/// <summary>The HTML <c>type</c> attribute of a <see cref="Button"/>.</summary>
public enum ButtonType
{
    /// <summary><c>type="button"</c>: no default form action.</summary>
    Button,

    /// <summary><c>type="submit"</c>: submits the enclosing form.</summary>
    Submit,

    /// <summary><c>type="reset"</c>: resets the enclosing form.</summary>
    Reset,
}
